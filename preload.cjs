const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd, arg) => cb(cmd, arg)),
  save: (data, path, forceDialog) => ipcRenderer.invoke('file:save', data, path, forceDialog),
  open: () => ipcRenderer.invoke('file:open'),
  exportFile: (ext, data, name) => ipcRenderer.invoke('file:export', ext, data, name),
  exportBinary: (ext, data, name) => ipcRenderer.invoke('file:exportBinary', ext, data, name),
  importFile: () => ipcRenderer.invoke('file:import'),
  savePdf: (html, name, opts) => ipcRenderer.invoke('pdf:save', html, name, opts),
  aiGenerate: (req) => ipcRenderer.invoke('ai:generate', req),
  shareStart: (html, glb) => ipcRenderer.invoke('share:start', html, glb),
  shareStop: () => ipcRenderer.invoke('share:stop'),
  libList: () => ipcRenderer.invoke('lib:list'),
  libGet: (url) => ipcRenderer.invoke('lib:get', url),
  openUpload: () => ipcRenderer.invoke('open:upload'),
  aiHasKey: () => ipcRenderer.invoke('ai:hasKey'),
  aiSetKey: (k) => ipcRenderer.invoke('ai:setKey', k),
  onAiProgress: (cb) => ipcRenderer.on('ai:progress', (_e, n) => cb(n)),
  versionAdd: (key, data) => ipcRenderer.send('version:add', key, data),
  versionList: (key) => ipcRenderer.invoke('version:list', key),
  versionRead: (key, name) => ipcRenderer.invoke('version:read', key, name),
  readFont: (file) => ipcRenderer.invoke('fonts:read', file),
  openPath: (p) => ipcRenderer.invoke('file:openPath', p),
  autosave: (data) => ipcRenderer.send('autosave:write', data),
  autosaveClear: () => ipcRenderer.send('autosave:clear'),
  autosaveRead: () => ipcRenderer.invoke('autosave:read'),
  setDirty: (d) => ipcRenderer.send('state', d),
  listPlugins: () => ipcRenderer.invoke('plugins:list'),
  setPluginMenu: (names) => ipcRenderer.send('plugins:menu', names),
});
